/**
 * Memory Service — contract types (T2.1).
 *
 * DESIGN ONLY. No runtime code, no I/O, no `falkordb` import.
 * This file is the compilable reference for `docs/contracts/memory-service.md`.
 * Implementation lands in T2.2–T2.4.
 *
 * Tenant isolation (D5): one named graph per tenant, key `tenant:<tenantId>`.
 * Every service call takes `tenant` first; callers never pass a graph key.
 */

/** Opaque tenant identifier. Maps to the FalkorDB graph key `tenant:<tenantId>`. */
export type TenantId = string;

/** Role of the actor that produced a Turn. */
export type TurnRole = 'user' | 'agent' | 'tool';

/** Lifecycle status of a recorded handoff. */
export type HandoffStatus = 'PENDING' | 'COMPLETED' | 'ALERT_RAISED' | 'PLAYBOOK_ENFORCED';

/** Unix epoch seconds (FalkorDB convention in the source guide). */
export type EpochSeconds = number;

// ---------------------------------------------------------------------------
// Shared node types
// ---------------------------------------------------------------------------

/** Episodic: a single message/event. The atomic episodic record. */
export interface Turn {
  id: string;
  timestamp: EpochSeconds;
  role: TurnRole;
  text: string;
  /** Optional quality signal, 0..1. */
  responseQuality?: number;
  /** Session this turn belongs to (`:IN_SESSION`). */
  sessionId?: string;
  /** User who participated (`:PARTICIPATED`), for user-authored turns. */
  userId?: string;
  /** Agent who produced the turn (`:PRODUCED`), for agent-authored turns. */
  agentId?: string;
  /** Topic name (`:ABOUT`). */
  topic?: string;
  /** Entity ids this turn mentions (`:MENTIONS`). */
  mentions?: string[];
}

/** Semantic: a durable domain object. */
export interface Entity {
  id: string;
  name: string;
  type: string;
  /** Optional vector; unused until a later decision record (ambiguity A7). */
  embedding?: number[];
}

/** Semantic: a durable assertion about the domain. */
export interface Fact {
  id: string;
  statement: string;
  /** 0..1. */
  confidence: number;
  /** Entity this fact concerns (`:HAS_FACT`). */
  entityId?: string;
  /** Provenance turn (`:DERIVED_FROM`); the edge is the source of truth (A3). */
  sourceTurn?: string;
}

/** Procedural: one action inside a workflow. */
export interface Step {
  id: string;
  order: number;
  action: string;
  expectedResult?: string;
}

/** Procedural: a reusable, re-executable sequence of steps. */
export interface Workflow {
  id: string;
  name: string;
  triggerDomain: string;
  /** Handoff this workflow was learned from (`:LEARNED_FROM`); edge is source of truth (A4). */
  learnedFrom?: string;
  steps: Step[];
  /** Tools the workflow invokes (`:USES`). */
  toolIds?: string[];
}

/** Coordination: one of the agent squad. */
export interface Agent {
  id: string;
  name: string;
  role: string;
  personaLevel: number;
}

/** Coordination: a recorded transfer of state and responsibility. */
export interface Handoff {
  id: string;
  createdAt: EpochSeconds;
  reason: string;
  status: HandoffStatus;
  fromAgentId: string;
  toAgentId: string;
  /** Semantic node the handoff concerns (`:TARGETS`). */
  targetEntityId?: string;
}

// ---------------------------------------------------------------------------
// Input / query shapes
// ---------------------------------------------------------------------------

export interface WriteTurnInput {
  /** Generated by the service if omitted. */
  id?: string;
  /** Defaults to now if omitted. */
  timestamp?: EpochSeconds;
  role: TurnRole;
  text: string;
  responseQuality?: number;
  sessionId?: string;
  userId?: string;
  agentId?: string;
  topic?: string;
  mentions?: string[];
}

export interface RecallTurnsQuery {
  userId?: string;
  sessionId?: string;
  topic?: string;
  limit?: number;
  /** Defaults to 'desc' (newest first). */
  order?: 'asc' | 'desc';
}

export interface UpsertEntityInput {
  id?: string;
  name: string;
  type: string;
  embedding?: number[];
}

export interface UpsertFactInput {
  id?: string;
  statement: string;
  confidence: number;
  entityId: string;
  sourceTurn?: string;
}

export interface RecallFactsQuery {
  entityId?: string;
  topic?: string;
  minConfidence?: number;
  limit?: number;
}

export interface QueryEntitiesQuery {
  name?: string;
  type?: string;
  limit?: number;
}

export interface SaveWorkflowInput {
  id?: string;
  name: string;
  triggerDomain: string;
  learnedFrom?: string;
  steps: Array<Omit<Step, 'id'> & { id?: string }>;
  toolIds?: string[];
}

/** Result of replaying a stored workflow. */
export interface WorkflowReplay {
  workflowId: string;
  steps: Step[];
}

export interface RecordHandoffInput {
  id?: string;
  /** Defaults to now if omitted. */
  createdAt?: EpochSeconds;
  reason: string;
  /** Defaults to 'PENDING' if omitted. */
  status?: HandoffStatus;
  fromAgentId: string;
  toAgentId: string;
  targetEntityId?: string;
}

export interface ReadHandoffsQuery {
  agentId?: string;
  status?: HandoffStatus;
  limit?: number;
}

// ---------------------------------------------------------------------------
// Service interface
// ---------------------------------------------------------------------------

/**
 * The single boundary for all three memory tiers plus coordination.
 * Every method takes `tenant` first and resolves to graph `tenant:<tenantId>`.
 */
export interface MemoryService {
  // Episodic
  writeTurn(tenant: TenantId, input: WriteTurnInput): Promise<Turn>;
  recallTurns(tenant: TenantId, query?: RecallTurnsQuery): Promise<Turn[]>;

  // Semantic
  upsertEntity(tenant: TenantId, input: UpsertEntityInput): Promise<Entity>;
  upsertFact(tenant: TenantId, input: UpsertFactInput): Promise<Fact>;
  recallFacts(tenant: TenantId, query: RecallFactsQuery): Promise<Fact[]>;
  queryEntities(tenant: TenantId, query: QueryEntitiesQuery): Promise<Entity[]>;

  // Procedural
  saveWorkflow(tenant: TenantId, input: SaveWorkflowInput): Promise<Workflow>;
  getWorkflow(tenant: TenantId, workflowId: string): Promise<Workflow | null>;
  replayWorkflow(tenant: TenantId, workflowId: string): Promise<WorkflowReplay>;

  // Coordination
  recordHandoff(tenant: TenantId, input: RecordHandoffInput): Promise<Handoff>;
  readHandoffs(tenant: TenantId, query?: ReadHandoffsQuery): Promise<Handoff[]>;
}
